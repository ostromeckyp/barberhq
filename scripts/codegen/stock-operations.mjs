// The demo supports six distinct products. Generate fixed, typed GraphQL groups
// so every stock change stays in one transaction; no runtime query construction.
import { writeFileSync, readFileSync } from "node:fs";
const count = 6;
const slots = Array.from({ length: count }, (_, i) => i);
const switches = slots.map((i) => `$use${i}:Boolean!`).join(",");
const prefix = slots
  .map((i) => `vars.use${i} == (vars.count > ${i})`)
  .join(" && ");
const base =
  "$uid:String!,$businessId:String!,$requestId:String!,$receiptId:String!,$key:String!,$payloadHash:String!,$semanticHash:String!";
const item = (i) =>
  `response.requestGuard.replenishmentRequest.items[vars.count > ${i} ? ${i} : 0]`;
const member = (salon) =>
  `membership(key:{uid:$uid}) @check(expr:"this != null && this.businessId == vars.businessId && this.role == '${salon ? "SALON" : "HQ"}'${salon ? " && this.salonAccesses_on_membership.exists(a, a.locationId == " + salon + ")" : ""}",message:"FORBIDDEN") {businessId role salonAccesses_on_membership {locationId}}`;
const submitter =
  'membership(key:{uid:$uid}) @check(expr:"this != null && this.businessId == vars.businessId && (this.role == \'HQ\' || (this.role == \'SALON\' && this.salonAccesses_on_membership.exists(a, a.locationId == vars.salonId)))",message:"FORBIDDEN") {businessId role salonAccesses_on_membership {locationId}}';
const receiver =
  'membership(key:{uid:$uid}) @check(expr:"this != null && this.businessId == vars.businessId && (this.role == \'HQ\' || (this.role == \'SALON\' && this.salonAccesses_on_membership.exists(a, a.locationId == response.requestGuard.replenishmentRequest.salonId)))",message:"FORBIDDEN") {businessId role salonAccesses_on_membership {locationId}}';
const audit = (
  action,
  state,
  revision,
) => `actionReceipt_insert(data:{id:$receiptId,businessId:$businessId,actorUid:$uid,idempotencyKey:$key,requestId:$requestId,action:${action},payloadHash:$payloadHash,semanticHash:$semanticHash,state:${state},revision_expr:"${revision}"${action === "REJECT" ? ",reason:$reason" : ""}})
  actionKey_insert(data:{businessId:$businessId,actorUid:$uid,idempotencyKey:$key,receiptId:$receiptId,payloadHash:$payloadHash})`;
let s = `# Generated by scripts/codegen/stock-operations.mjs. Edit the generator, then regenerate.
query StockContext($uid:String!,$requestId:String,$salonId:String,$productIds:[String!]!,$key:String!,$action:StockActionType!) @auth(level:NO_ACCESS) {
 membership(key:{uid:$uid}) {uid businessId role salonAccesses_on_membership {locationId} business {locations_on_business(where:{kind:{eq:HQ}},limit:1){id}}}
 replenishmentRequest(first:{where:{id:{eq:$requestId}}}) {id businessId salonId state revision items:requestItems_on_request(orderBy:{productId:ASC}) {id productId quantity product {inventories_on_product {locationId onHand reserved version}}}}
 products(where:{id:{in:$productIds}},limit:6){id businessId}
 location(first:{where:{id:{eq:$salonId}}}) {id businessId kind}
 keyed:actionKeys(where:{actorUid:{eq:$uid},idempotencyKey:{eq:$key}},limit:1){payloadHash receipt{id businessId requestId actorUid action payloadHash semanticHash state revision}}
 semantic:actionReceipts(where:{requestId:{eq:$requestId},action:{eq:$action}},limit:1){id businessId requestId actorUid action payloadHash semanticHash state revision}
 activeRequests(where:{salonId:{eq:$salonId},productId:{in:$productIds}},orderBy:{productId:ASC},limit:6){requestId productId}
}
mutation SubmitStock(${base},$salonId:String!,$productIds:[String!]!,$itemIds:[String!]!,$quantities:[Int!]!,$count:Int!,${switches}) @auth(level:NO_ACCESS) @transaction {
 query @redact {
  ${submitter}
  location(id:$salonId) @check(expr:"this != null && this.businessId == vars.businessId && this.kind == 'SALON'",message:"FORBIDDEN"){businessId kind}
  products(where:{id:{in:$productIds},businessId:{eq:$businessId}},limit:6) @check(expr:"vars.count >= 1 && vars.count <= 6 && vars.productIds.size() == vars.count && vars.itemIds.size() == vars.count && vars.quantities.size() == vars.count && this.size() == vars.count && vars.quantities.all(q,q >= 1 && q <= 99) && ${prefix}",message:"VALIDATION_ERROR"){id}
 }
 replenishmentRequest_insert(data:{id:$requestId,businessId:$businessId,salonId:$salonId,state:PENDING_APPROVAL,revision:1})
`;
for (const i of slots)
  s += ` item${i}:requestItem_insert(data:{id_expr:"vars.itemIds[vars.count > ${i} ? ${i} : 0]",requestId:$requestId,productId_expr:"vars.productIds[vars.count > ${i} ? ${i} : 0]",quantity_expr:"vars.quantities[vars.count > ${i} ? ${i} : 0]"}) @include(if:$use${i})
 active${i}:activeRequest_insert(data:{businessId:$businessId,salonId:$salonId,productId_expr:"vars.productIds[vars.count > ${i} ? ${i} : 0]",requestId:$requestId}) @include(if:$use${i})
`;
s += audit("SUBMIT", "PENDING_APPROVAL", "1") + "\n}\n";
for (const [action, from, to] of [
  ["APPROVE", "PENDING_APPROVAL", "RESERVED"],
  ["REJECT", "PENDING_APPROVAL", "REJECTED"],
  ["DISPATCH", "RESERVED", "DISPATCHED"],
  ["RECEIVE", "DISPATCHED", "RECEIVED"],
]) {
  const name = {
    APPROVE: "Approve",
    REJECT: "Reject",
    DISPATCH: "Dispatch",
    RECEIVE: "Receive",
  }[action];
  const extras =
    action === "APPROVE"
      ? "$inventoryVersions:[Int!]!,"
      : action === "REJECT"
        ? "$reason:String!,"
        : action === "RECEIVE"
          ? "$receivedQuantities:[Int!]!,$allIntact:Boolean!,"
          : "";
  const indexed = action !== "REJECT";
  s += `mutation ${name}Stock(${base},$revision:Int!,$count:Int!,${extras}${indexed ? switches : ""}) @auth(level:NO_ACCESS) @transaction {
 requestGuard:query @redact {
  replenishmentRequest(id:$requestId) @check(expr:"this != null && this.businessId == vars.businessId && this.state == '${from}' && this.revision == vars.revision && vars.count >= 1 && vars.count <= 6 && this.items.size() == vars.count${indexed ? " && " + prefix : ""}${action === "APPROVE" ? " && vars.inventoryVersions.size() == vars.count" : ""}${action === "RECEIVE" ? " && vars.receivedQuantities.size() == vars.count && vars.allIntact" : ""}${action === "REJECT" ? " && vars.reason.size() >= 1 && vars.reason.size() <= 500" : ""}",message:"STALE_STATE"){businessId salonId state revision items:requestItems_on_request(orderBy:{productId:ASC}){id productId quantity}}
 }
 actor:query @redact {${action === "RECEIVE" ? receiver : member(false)}
  ${action === "APPROVE" ? 'locations(where:{businessId:{eq:$businessId},kind:{eq:HQ}},limit:2) @check(expr:"this.size() == 1",message:"INVALID_TRANSITION"){id}' : ""}
 }
 changed:replenishmentRequest_updateMany(where:{id:{eq:$requestId},businessId:{eq:$businessId},state:{eq:${from}},revision:{eq:$revision}},data:{state:${to},revision_update:{inc:1}}) @check(expr:"this == 1",message:"STALE_STATE")
`;
  if (action === "APPROVE")
    s += ` transfer_insert(data:{requestId:$requestId,businessId:$businessId,warehouseId_expr:"response.actor.locations[0].id",destinationId_expr:"response.requestGuard.replenishmentRequest.salonId"})\n`;
  if (indexed)
    for (const i of slots) {
      const ref = item(i),
        stock = (field) =>
          `(vars.count > ${i} ? response.stock${i}.inventories[0].${field} : response.stock0.inventories[0].${field})`;
      const where =
        action === "RECEIVE"
          ? `locationId:{eq_expr:"response.requestGuard.replenishmentRequest.salonId"}`
          : `location:{businessId:{eq:$businessId},kind:{eq:HQ}}`;
      const condition =
        action === "APPROVE"
          ? ` && this[0].version == vars.inventoryVersions[vars.count > ${i} ? ${i} : 0] && this[0].onHand - this[0].reserved >= ${ref}.quantity`
          : action === "DISPATCH"
            ? ` && this[0].onHand >= ${ref}.quantity && this[0].reserved >= ${ref}.quantity`
            : ` && vars.receivedQuantities[vars.count > ${i} ? ${i} : 0] == ${ref}.quantity`;
      s += ` stock${i}:query @redact @include(if:$use${i}){inventories(where:{${where},productId:{eq_expr:"${ref}.productId"}},limit:2) @check(expr:"this.size() == 1${condition}",message:"STALE_STATE"){locationId productId onHand reserved version}}
 update${i}:inventory_updateMany(where:{locationId:{eq_expr:"${stock("locationId")}"},productId:{eq_expr:"${ref}.productId"},version:{eq_expr:"${stock("version")}"}},data:{version_update:{inc:1},${action === "RECEIVE" ? `onHand_expr:"${stock("onHand")} + ${ref}.quantity"` : `reserved_expr:"${stock("reserved")} ${action === "APPROVE" ? "+" : "-"} ${ref}.quantity"${action === "DISPATCH" ? `,onHand_expr:"${stock("onHand")} - ${ref}.quantity"` : ""}`}}) @include(if:$use${i}) @check(expr:"this == 1",message:"STALE_STATE")
`;
      if (action === "APPROVE")
        s += ` transfer${i}:transferItem_insert(data:{requestItemId_expr:"${ref}.id",transferRequestId:$requestId,quantity_expr:"${ref}.quantity"}) @include(if:$use${i})\n`;
      else {
        s += ` transfer${i}:transferItem_updateMany(where:{requestItemId:{eq_expr:"${ref}.id"},transferRequestId:{eq:$requestId},quantity:{eq_expr:"${ref}.quantity"},${action === "DISPATCH" ? "dispatchedQuantity:{eq:0},receivedQuantity:{eq:0}" : `dispatchedQuantity:{eq_expr:"${ref}.quantity"},receivedQuantity:{eq:0}`}},data:{${action === "DISPATCH" ? "dispatchedQuantity" : "receivedQuantity"}_expr:"${ref}.quantity"}) @include(if:$use${i}) @check(expr:"this == 1",message:"INVALID_TRANSITION")
 movement${i}:stockMovement_insert(data:{transferItemRequestItemId_expr:"${ref}.id",businessId:$businessId,type:${action === "DISPATCH" ? "DISPATCH" : "RECEIPT"},quantity_expr:"${ref}.quantity",actorUid:$uid}) @include(if:$use${i})
`;
      }
    }
  if (action === "REJECT" || action === "RECEIVE")
    s += ` activeRequest_deleteMany(where:{requestId:{eq:$requestId},businessId:{eq:$businessId}}) @check(expr:"this == vars.count",message:"INVALID_TRANSITION")\n`;
  s += audit(action, to, "vars.revision + 1") + "\n}\n";
}
const replay = readFileSync(
  new URL("./replay-key.gql", import.meta.url),
  "utf8",
);
writeFileSync(
  new URL("../../dataconnect/server/stock.gql", import.meta.url),
  s + "\n" + replay,
);
